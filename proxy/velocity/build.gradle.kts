// UniversalAdmin for Velocity - an optional proxy plugin for network mode:
// turns banned players away at the proxy itself, before they reach any
// server (also servers that do not run UniversalAdmin), and keeps it closed
// during network maintenance and to players not on the network whitelist.
// The checks are proxy/common; this is the Velocity adapter. Reads the same
// MySQL/MariaDB database as the servers; it never writes to it.
//
// Built against the Velocity 3.4 API with Java 21 bytecode, so one jar runs
// on Velocity 3.4+ (Java 21) and Velocity 4.x.

import com.github.jengelman.gradle.plugins.shadow.tasks.ShadowJar

plugins {
    java
    id("com.gradleup.shadow")
}

group = "dev.universaladmin.velocity"
version = rootProject.version
base.archivesName.set("universaladmin-velocity")

java {
    toolchain {
        languageVersion.set(JavaLanguageVersion.of(25))
    }
}

repositories {
    mavenCentral()
    maven("https://repo.papermc.io/repository/maven-public/") { name = "papermc" }
}

dependencies {
    compileOnly("com.velocitypowered:velocity-api:3.4.0")
    annotationProcessor("com.velocitypowered:velocity-api:3.4.0")
    // The checks, with the same driver and pool as the plugin (relocated below).
    implementation(project(":universaladmin-proxy-common"))
}

tasks.withType<JavaCompile>().configureEach {
    options.encoding = "UTF-8"
    options.release.set(21)
    options.compilerArgs.add("-parameters")
}

// The @Plugin annotation needs the version as a compile-time constant.
val generateBuildConstants = tasks.register("generateBuildConstants") {
    val outputDir = layout.buildDirectory.dir("generated/sources/buildConstants")
    val projectVersion = project.version.toString()
    inputs.property("version", projectVersion)
    outputs.dir(outputDir)
    doLast {
        val file = outputDir.get().file("dev/universaladmin/velocity/BuildConstants.java").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package dev.universaladmin.velocity;
            |
            |/** Generated by the build. */
            |final class BuildConstants {
            |
            |    static final String VERSION = "$projectVersion";
            |
            |    private BuildConstants() {
            |    }
            |}
            |""".trimMargin()
        )
    }
}

sourceSets.main {
    java.srcDir(generateBuildConstants)
}

tasks.named<ShadowJar>("shadowJar") {
    archiveClassifier.set("")
    relocate("org.mariadb", "dev.universaladmin.velocity.libs.mariadb")
    relocate("com.zaxxer.hikari", "dev.universaladmin.velocity.libs.hikari")
    mergeServiceFiles()
}

tasks.jar {
    archiveClassifier.set("plain")
}

tasks.build {
    dependsOn(tasks.shadowJar)
}
